// Verify every level: solvable with the concepts, unsolvable under "ordinary" rules.
// Writes docs/process-v2/solver-report.md.
const fs = require('fs');
const path = require('path');
const { LEVELS, THREADS } = require('../src/levels.js');
const S = require('../src/solver.js');

function solves(L, rules) {
  if (L.alternatives) return S.solveBelief(L, S.openingWorlds(L), rules) ? 'WIN' : 'no';
  const r = S.solveFull(L, rules);
  return r.status === 'solved' ? 'WIN' : r.status === 'limit' ? 'LIMIT' : 'no';
}

const RULES = {
  greedy: { greedyBloom: true, label: 'more open = more urgent (monotonic reading)' },
  noSummon: { noSummon: true, label: 'never call the Owl (checks just happen to you)' },
};

const rows = [];
let failures = 0;
for (const L of LEVELS) {
  const full = solves(L, {});
  const greedy = solves(L, RULES.greedy);
  const noSummon = L.owl ? solves(L, RULES.noSummon) : '-';
  const thread = THREADS[L.thread];
  // What each thread must demonstrate.
  let need = [];
  if (L.thread === 0) need = ['greedy'];
  if (L.thread === 1) need = ['noSummon'];
  if (L.thread === 2) need = ['greedy', 'noSummon'];
  const results = { greedy, noSummon };
  let ok = full === 'WIN' && (L.tutorial || need.every(k => results[k] === 'no'));
  if (!ok) failures++;
  rows.push({ L, thread, full, greedy, noSummon, ok });
}

const lines = [];
lines.push('# Solver report');
lines.push('');
lines.push('Generated by `node tools/check-levels.js`. Every level is searched exhaustively over action sequences');
lines.push('breath by breath. Levels with fogged history (`Listen`) are checked with the partial-observation');
lines.push('solver: one policy must win in every world consistent with what the player can see.');
lines.push('');
lines.push('Columns:');
lines.push('- **With the concepts**: the full action set. `WIN` means a winning plan or policy exists.');
lines.push(`- **Monotonic reading**: ${RULES.greedy.label}. Each water must go to a currently most-open flower.`);
lines.push(`- **No capture**: ${RULES.noSummon.label}.`);
lines.push('- **Required**: what the level must show. Thirst levels need fold-back thinking, Owl levels need capture, and Glass levels need both.');
lines.push('');
lines.push('| Level | Thread | With the concepts | Monotonic reading | No capture | Required | OK |');
lines.push('|---|---|---|---|---|---|---|');
for (const r of rows) {
  const req = r.L.tutorial ? 'tutorial' : r.L.thread === 0 ? 'fold-back' : r.L.thread === 1 ? 'capture' : 'both';
  lines.push(`| ${r.L.id} ${r.L.name} | ${r.thread} | ${r.full} | ${r.greedy} | ${r.noSummon} | ${req} | ${r.ok ? '✓' : '✗'} |`);
}
lines.push('');
lines.push(failures ? `**${failures} level(s) fail their claims.**` : 'All levels meet their claims.');
fs.writeFileSync(path.join(__dirname, '../docs/process-v2/solver-report.md'), lines.join('\n') + '\n');
console.log(lines.slice(-rows.length - 4).join('\n'));
process.exitCode = failures ? 1 : 0;

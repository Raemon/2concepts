// Check every level: solvable with the ideas its thread teaches, and NOT solvable without them.
//   node tools/check-levels.js            -> table + docs/process-v2/solver-report.md
//   node tools/check-levels.js waving     -> one level, with its plan
const SW = require('../src/logic.js');
const { LEVELS } = require('../src/levels.js');
const Solver = require('../src/solver.js');
const fs = require('fs');
const path = require('path');

// Which restricted policies must FAIL on each thread. The tutorial is exempt.
const MUST_FAIL = {
  first: [],
  quiet: ['ordinary'],
  waving: ['ordinary', 'noWhistle'],
  rush: ['ordinary', 'noWhistle'],
  inspect: [],
  timing: ['noCall'],
  twice: ['noCall'],
  clean: ['ordinary', 'noCall'],
  last: ['ordinary', 'noCall', 'noWhistle'],
};

const HUMAN = { react: 0.9, whistleEvery: 4 };
const stars = {};
const only = process.argv[2];
const rows = [];
let bad = 0;
for (const L of LEVELS) {
  if (only && L.id !== only) continue;
  const t0 = Date.now();
  const full = Solver.solve(L, 'full');
  // a relaxed human: slower to react, whistles only every 4 seconds
  const human = Solver.solve(L, 'full', HUMAN);
  const row = { id: L.id, name: L.name, thread: L.thread, full, human, others: {}, ms: 0 };
  for (const p of MUST_FAIL[L.id] || []) row.others[p] = Solver.solve(L, p);
  row.ms = Date.now() - t0;
  const rep = full.ok ? Solver.replay(L, full.plan) : null;
  row.replay = rep;
  const okFull = full.ok && rep.over === 'won' && human.ok;
  if (full.ok) stars[L.id] = [Math.round(0.75 * rep.score / 10) * 10, Math.round(0.92 * rep.score / 10) * 10];
  const okOthers = Object.values(row.others).every(r => !r.ok && !r.aborted);
  if (!okFull || !okOthers) bad++;
  rows.push(row);
  const o = Object.entries(row.others).map(([k, r]) => `${k}:${r.ok ? 'SOLVED(bad)' : r.aborted ? 'ABORTED' : 'no'}(${r.nodes})`).join(' ');
  console.log(`${okFull && okOthers ? 'OK ' : 'BAD'} ${L.id.padEnd(8)} full:${full.ok ? 'yes' : full.aborted ? 'ABORTED' : 'no'}(${full.nodes}) human:${human.ok ? 'yes' : 'NO'} score ${rep ? rep.score : '-'}  ${o}  ${row.ms}ms`);
  if (only && full.ok) for (const s of full.plan) console.log('   ', s.t.toFixed(2), s.a, s.who != null ? `#${s.who}` : '', s.x != null ? `(${s.x.toFixed(2)},${s.y.toFixed(2)})` : '');
  if (only) for (const [k, r] of Object.entries(row.others)) {
    console.log('   ', k, r.ok ? 'SOLVED' : 'no plan', r.nodes, 'nodes');
    if (r.ok) for (const s of r.plan) console.log('       ', s.t.toFixed(2), s.a, s.who != null ? `#${s.who}` : '');
  }
}
if (!only) {
  const lines = ['# Solver report: STILL WATER', '',
    'Generated by `node tools/check-levels.js`. The solver plays with perfect aim and a 0.3 s reaction time, deciding every',
    '0.25 s. Its search is exhaustive over that grid, so "no plan" means no line of play exists at that grain.', '',
    'Policies:', '',
    '- **full**: every idea the game teaches.',
    '- **ordinary**: the Captain\'s own rule. Only someone yelling gets a ring; a quiet swimmer is a fine swimmer.',
    '- **noWhistle**: knows silence can be worse, but can\'t probe with the whistle. A quiet drowner is spotted only once',
    `  they are visibly sinking (${Solver.VISIBLE * 100}% of the way under), or if they were seen yelling first.`,
    '- **noCall**: never radios the Captain in; waits for his scheduled visits.', '',
    `Every level must also be won by a **relaxed human** model: the full policy with a ${HUMAN.react} s reaction time that`,
    `whistles only every ${HUMAN.whistleEvery} s.`, '',
    '| Level | Thread | full | relaxed human | must fail | result |', '|---|---|---|---|---|---|'];
  for (const r of rows) {
    const o = Object.entries(r.others).map(([k, v]) => `${k}: ${v.ok ? '**solved**' : 'no plan'} (${v.nodes} nodes)`).join('<br>') || '(tutorial)';
    const acts = r.full.ok ? r.full.plan.filter(s => !s.routine).length : 0;
    lines.push(`| ${r.name} | ${r.thread} | ${r.full.ok ? `won, ${r.replay.score} pts, ${acts} throws/calls` : 'NO PLAN'} | ${r.human.ok ? 'won' : '**no plan**'} | ${o} | ${r.full.ok && r.human.ok && Object.values(r.others).every(v => !v.ok) ? 'ok' : 'FAIL'} |`);
  }
  lines.push('', '## Winning plans', '');
  for (const r of rows) {
    if (!r.full.ok) continue;
    lines.push(`**${r.name}** (routine whistles omitted): ` + r.full.plan.filter(s => !s.routine).map(s => `${s.t.toFixed(2)} ${s.a}${s.who != null ? ' #' + s.who : ''}`).join(' · '), '');
  }
  fs.writeFileSync(path.join(__dirname, '../docs/process-v2/solver-report.md'), lines.join('\n') + '\n');
  // star thresholds: 2 stars at 75% of the solver's score, 3 stars at 92%
  const lp = path.join(__dirname, '../src/levels.js');
  const src = fs.readFileSync(lp, 'utf8').replace(/const STARS = \{[^}]*\};/, `const STARS = { ${Object.entries(stars).map(([k, v]) => `${k}: [${v.join(', ')}]`).join(', ')} };`);
  fs.writeFileSync(lp, src);
  console.log(bad ? `${bad} level(s) failed` : 'all levels ok');
  process.exitCode = bad ? 1 : 0;
}
